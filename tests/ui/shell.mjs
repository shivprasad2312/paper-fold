// Non-game shell regression. Run with a local Vite/preview server.
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import puppeteer from 'puppeteer-core';
import chromium from '@sparticuz/chromium';
const OUT=process.env.OUT || 'shots/shell';
const BASE=process.env.URL || 'http://localhost:4173/';
mkdirSync(OUT,{recursive:true});
const browser=await puppeteer.launch({executablePath:await chromium.executablePath(),args:[...chromium.args,'--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'],headless:'shell'});
const page=await browser.newPage();
const errors=[];const external=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(!r.url().startsWith(BASE) && /^https?:/.test(r.url()))external.push(r.url());});
const wait=ms=>new Promise(r=>setTimeout(r,ms));
const visible=selector=>page.waitForSelector(selector,{visible:true,timeout:15000});
const shot=async name=>{await wait(200);await page.screenshot({path:`${OUT}/${name}.png`});};
const overflow=async selector=>page.$eval(selector,e=>e.scrollWidth>e.clientWidth+1);
try {
  await page.setViewport({width:1440,height:960});
  await page.goto(BASE,{waitUntil:'networkidle0'});
  await page.waitForFunction(()=>!!window.__kubik,{timeout:30000});
  await page.evaluate(()=>document.fonts.ready);
  assert.equal(await overflow('#menu'),false);
  assert.equal(await page.$eval('#home-progress',e=>e.getAttribute('aria-valuenow')),'0');
  await shot('01-home-dark');
  await page.click('#menu [data-open-dialog="settings"]');
  await visible('#settings');
  assert.equal(await page.$eval('#menu',e=>e.inert),true);
  await page.focus('#btn-sound-menu');await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')),'Close settings');
  const before=await page.evaluate(()=>window.__kubik.game.moves);
  await page.keyboard.press('r');await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(()=>window.__kubik.game.moves),before);
  assert.equal(await page.$eval('#settings',e=>e.classList.contains('hidden')),true);
  // Enter activated the focused Close button, not the game's Play shortcut.
  assert.equal(await page.$eval('#menu',e=>e.classList.contains('hidden')),false);
  await page.click('#menu [data-open-dialog="settings"]');
  await page.click('#btn-theme-menu');
  assert.equal(await page.evaluate(()=>document.body.classList.contains('light')),true);
  await page.click('#btn-motion-menu');
  assert.equal(await page.evaluate(()=>window.__kubik.save.motion),'reduced');
  await page.click('#btn-sound-menu');
  assert.equal(await page.$eval('#btn-sound-menu',e=>e.getAttribute('aria-pressed')),'false');
  await shot('02-settings-light');
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.openDialog),'settings');
  await shot('03-home-light');
  await page.reload({waitUntil:'networkidle0'});await page.waitForFunction(()=>!!window.__kubik);
  assert.equal(await page.evaluate(()=>document.body.classList.contains('light')),true);
  assert.equal(await page.evaluate(()=>document.body.classList.contains('reduce-motion')),true);
  await page.click('#btn-levels');await visible('#levels');
  assert.equal(await page.$$eval('#level-grid .level-card',els=>els.length),211);
  assert.equal(await page.$$eval('#level-grid .level-card:not(.vault-card):disabled',els=>els.length),0);
  await shot('04-collection-light');
  await page.click('[data-world="world-10"]');await wait(150);
  assert.ok(await page.$eval('.levels-inner',e=>e.scrollTop)>0);
  await page.keyboard.press('Escape');await visible('#menu');
  await page.click('#menu [data-open-dialog="settings"]');await page.click('#btn-theme-menu');await page.keyboard.press('Escape');
  await page.setViewport({width:390,height:844});
  await shot('05-home-mobile');
  assert.equal(await overflow('#menu'),false);
  await page.click('#menu [data-open-dialog="settings"]');await visible('#settings');
  assert.equal(await overflow('#settings .panel'),false);
  await shot('06-settings-mobile');await page.keyboard.press('Escape');
  await page.click('#btn-levels');await visible('#levels');
  assert.equal(await overflow('#levels'),false);
  assert.equal(await overflow('.levels-inner'),false);
  await shot('07-collection-mobile');
  await page.click('#level-grid .level-card:not(.daily-card)');
  await page.waitForFunction(()=>window.__kubik.game.playing);
  await page.keyboard.press('Escape');await visible('#pause');await shot('08-pause-mobile');
  await page.click('#pause [data-open-dialog="settings"]');await visible('#settings');
  await page.keyboard.press('Escape');assert.equal(await page.evaluate(()=>window.__kubik.game.paused),true);
  await page.click('#btn-resume');assert.equal(await page.evaluate(()=>window.__kubik.game.paused),false);
  await page.keyboard.press('ArrowUp');await wait(400);
  assert.ok(await page.evaluate(()=>window.__kubik.game.moves)>0,'game input still works');
  // Render the real completion event for layout coverage, not a playability proof.
  await page.evaluate(()=>window.__kubik.game.win());await visible('#win');await shot('09-completion-mobile');
  assert.equal(await overflow('#win .panel'),false);
  await page.click('#btn-win-levels');await visible('#levels');
  // Daily has no Next action. A fresh dialog (no prior focus history)
  // must skip that hidden CTA when choosing its initial control.
  await page.reload({waitUntil:'networkidle0'});await page.waitForFunction(()=>!!window.__kubik);
  await page.evaluate(()=>{window.__kubik.startDaily();window.__kubik.game.win();});
  await visible('#win');
  assert.equal(await page.$eval('#btn-next',e=>getComputedStyle(e).display),'none');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'btn-replay');
  await page.click('#btn-win-levels');await visible('#levels');
  await page.setViewport({width:320,height:640});
  assert.equal(await overflow('#levels'),false);
  assert.equal(await overflow('.levels-inner'),false);
  await page.click('#btn-levels-back');await visible('#menu');
  assert.equal(await overflow('#menu'),false);
  await shot('10-home-small');
  assert.deepEqual(errors,[],'no browser errors');
  assert.deepEqual(external,[],'no third-party requests');
  console.log('Shell regression passed: desktop / mobile / 320px, themes, persisted settings, focus, navigation, pause, completion, game input; zero page errors / external requests.');
} finally { await browser.close(); }
